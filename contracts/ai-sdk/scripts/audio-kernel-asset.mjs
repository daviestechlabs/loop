import { readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';

const root = new URL('../', import.meta.url);
const hash = createHash('sha256');
for (const file of ['wasm/audio_kernel.c', 'wasm/audio_kernel.h', 'scripts/build-audio-wasm.sh', 'scripts/audio-kernel-asset.mjs']) {
  hash.update(file + '\0').update(readFileSync(new URL(file, root))).update('\0');
}
const fingerprint = hash.digest('hex');
const target = new URL('src/audioWasm.ts', root);
if (process.argv.length === 4) {
  let source = '// Generated by scripts/build-audio-wasm.sh.\n' +
    `export const AUDIO_KERNEL_SOURCE_SHA256 = "${fingerprint}";\n`;
  for (const [index, kind] of ['SCALAR', 'SIMD'].entries()) {
    const bytes = readFileSync(process.argv[index + 2]);
    const module = new WebAssembly.Module(bytes);
    if (WebAssembly.Module.imports(module).length) throw new Error('Audio kernel must have no host imports');
    const encoded = bytes.toString('base64').match(/.{1,120}/g).map(JSON.stringify).join(' +\n  ');
    source += `export const ${kind}_AUDIO_KERNEL_BASE64 =\n  ${encoded};\n`;
    console.log(`${kind} C audio kernel: ${bytes.length} bytes, no host imports`);
  }
  writeFileSync(target, source);
} else if (!readFileSync(target, 'utf8').includes(`AUDIO_KERNEL_SOURCE_SHA256 = "${fingerprint}"`)) {
  throw new Error('C audio sources changed; rebuild the embedded WebAssembly modules');
} else {
  console.log('C audio source fingerprint matches the embedded modules');
}
