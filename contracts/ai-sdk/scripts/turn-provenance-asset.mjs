import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";

const root = fileURLToPath(new URL("../../../", import.meta.url));
const manifest = "contracts/ai-sdk/wasm/turn_provenance.sources";
const target = path.join(root, "contracts/ai-sdk/src/turnProvenanceWasm.ts");
const hash = createHash("sha256");
for (const file of readFileSync(path.join(root, manifest), "utf8").trim().split("\n")) {
  hash.update(file + "\0").update(readFileSync(path.join(root, file))).update("\0");
}
const fingerprint = hash.digest("hex");
if (process.argv[2]) {
  const bytes = readFileSync(process.argv[2]);
  const module = new WebAssembly.Module(bytes);
  if (WebAssembly.Module.imports(module).length) throw new Error("Provenance module must have no host imports");
  const encoded = bytes.toString("base64").match(/.{1,120}/g).map((line) => JSON.stringify(line)).join(" +\n  ");
  writeFileSync(target, "// Generated by scripts/build-turn-provenance-wasm.sh.\n" +
    `export const TURN_PROVENANCE_SOURCE_SHA256 = "${fingerprint}";\n` +
    `export const TURN_PROVENANCE_WASM_BASE64 =\n  ${encoded};\n`);
  console.log(`Built C turn provenance module: ${bytes.length} bytes; no host imports`);
} else {
  if (!readFileSync(target, "utf8").includes(`TURN_PROVENANCE_SOURCE_SHA256 = "${fingerprint}"`)) {
    throw new Error("C turn provenance sources changed; rebuild the embedded WebAssembly module");
  }
  console.log("C turn provenance source fingerprint matches the embedded module");
}
